//=,==,===,!=,!==,>,<,>=,<=
let x=10;
let y='10';
console.log(x==y); // true (loose comparison)
console.log(x===y); // false (strict comparison)
console.log(x!=y); // false
console.log(x!==y); // true
console.log(x>y); // false
console.log(x<y); // false
console.log(x>=y); // true
console.log(x<=y); // true  
